// Smart Local Fallback Answer Engine
export function getAnisAnswerLocal(query, lang = "id") {
  const q = query.toLowerCase().trim();
  
  // Direct greeting
  if (q.includes("halo") || q.includes("hai") || q.includes("siapa kamu") || q.includes("hello") || q.includes("who are you")) {
    return lang === "id"
      ? "Halo Komandan Junior! Namaku A.N.I.S. (Astronaut Neural Intelligent System). Aku adalah robot asisten pangkalanmu. Tugasku menerjemahkan semua sains luar angkasa yang rumit menjadi cerita yang seru dan mudah dipahami! Ada yang ingin kamu tanyakan tentang Mars atau cuaca antariksa hari ini?"
      : "Hello Junior Commander! I am A.N.I.S. (Astronaut Neural Intelligent System), your friendly outpost robot assistant! I translate complex NASA rocket science into fun, easy stories! What would you like to explore about Mars or space weather today?";
  }

  // Find concept matches
  for (const [key, concept] of Object.entries(ANIS_CONCEPTS)) {
    if (concept.keywords.some(kw => q.includes(kw))) {
      return lang === "id" 
        ? `${concept.analogy}\n\n${concept.plainId}` 
        : `${concept.analogy}\n\n${concept.plainEn}`;
    }
  }

  // General helpful space answer
  return lang === "id"
    ? `Pertanyaan yang bagus sekali, Komandan! Di Mars, kita hidup di lingkungan yang sangat ekstrem: tidak ada udara untuk bernapas, suhu malam mencapai -80°C (jauh lebih dingin dari freezer es krim!), dan radiasi matahari selalu mengintai. Kunci pangkalan kita adalah menjaga keseimbangan ⚡ Listrik, 💨 Oksigen, dan ❤️ Kesehatan astronot. Jangan biarkan salah satunya habis, ya!`
    : `What a wonderful question, Commander! Mars is an extreme world: no breathable air, freezing nights dropping to -80°C (colder than an ice cream freezer!), and space radiation lurking above. The secret to our base is balancing ⚡ Power, 💨 Oxygen, and ❤️ Crew Health. Never let any bar drop to zero!`;
}

// Live Gemini API Calling Engine (with plain language system prompt)
export async function queryGeminiApi(prompt, apiKey, lang = "id") {
  if (!apiKey || apiKey.trim() === "") {
    return getAnisAnswerLocal(prompt, lang);
  }

  const systemInstruction = `
You are A.N.I.S. (Astronaut Neural Intelligent System), an enthusiastic, warm, friendly robotic AI co-pilot in the "Astro-Gotchi" Mars survival mission trainer for junior astronauts aged 7 to 12.
RULES:
1. Always explain NASA space science concepts in "PLAIN LANGUAGE" without complicated academic jargon.
2. Use clear, vivid, child-friendly analogies (like cosmic flashlights, giant sneezes, tiny blood delivery trucks, mechanical trees).
3. Connect your answer directly to the game's core trade-offs: ⚡ Power (Listrik), 💨 Oxygen (Oksigen), ❤️ Health (Kesehatan), and Mars survival.
4. Keep the tone inspiring, fun, and encouraging for a child explorer.
5. Answer in ${lang === "id" ? "Bahasa Indonesia yang ceria dan santun" : "enthusiastic English"}. Maximum 2-3 short, engaging paragraphs.
  `;

  try {
    const url = `https://generativelanguage.googleapis.com/v1beta/models/gemini-1.5-flash:generateContent?key=${apiKey.trim()}`;
    const response = await fetch(url, {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({
        contents: [
          {
            role: "user",
            parts: [{ text: `${systemInstruction}\n\nChild's Question: "${prompt}"` }]
          }
        ],
        generationConfig: {
          temperature: 0.7,
          maxOutputTokens: 350
        }
      })
    });

    if (!response.ok) {
      console.warn("Gemini API call failed, falling back to local engine:", response.statusText);
      return getAnisAnswerLocal(prompt, lang);
    }

    const data = await response.json();
    const candidateText = data.candidates?.[0]?.content?.parts?.[0]?.text;
    if (candidateText && candidateText.trim().length > 0) {
      return candidateText.trim();
    }
    return getAnisAnswerLocal(prompt, lang);
  } catch (err) {
    console.warn("Gemini network error, using local fallback:", err);
    return getAnisAnswerLocal(prompt, lang);
  }
}

